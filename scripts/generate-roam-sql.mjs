import { readFileSync, writeFileSync } from "node:fs";
import { registerHooks } from "node:module";
import { fileURLToPath } from "node:url";

registerHooks({
  resolve(specifier, context, next) {
    try { return next(specifier, context); }
    catch (error) {
      if (error.code === "ERR_MODULE_NOT_FOUND" && specifier.startsWith(".")) return next(`${specifier}.ts`, context);
      throw error;
    }
  },
});

const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
  throw new Error("Usage: node scripts/generate-roam-sql.mjs [--check]");
}
const { captureSql } = await import("../packages/db-core/src/roam/generate.ts");
const scopes = ["global", "repo", "worktree"];
const literal = value => `\`${value.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${")}\``;
const entries = scopes.map(scope => {
  const sql = captureSql(scope);
  const matches = [...sql.matchAll(/^CREATE TRIGGER ([a-z0-9_]+)\b[\s\S]*?^END;/gm)];
  if (matches.map(match => match[0]).join("\n") !== sql || new Set(matches.map(match => match[1])).size !== matches.length) {
    throw new Error(`Invalid generated trigger sequence for ${scope}`);
  }
  return `  ${scope}: [\n${matches.map(match => `    { name: ${JSON.stringify(match[1])}, sql: ${literal(match[0])} },`).join("\n")}\n  ],`;
}).join("\n");
const output = `// Generated by scripts/generate-roam-sql.mjs. Do not edit.\nimport type { Scope } from "./types";\n\nexport interface GeneratedTrigger { readonly name: string; readonly sql: string }\n\nexport const GENERATED_TRIGGERS: Readonly<Record<Scope, readonly GeneratedTrigger[]>> = {\n${entries}\n};\n\nexport const GENERATED_CAPTURE_SQL: Readonly<Record<Scope, string>> = {\n  global: GENERATED_TRIGGERS.global.map(trigger => trigger.sql).join("\\n"),\n  repo: GENERATED_TRIGGERS.repo.map(trigger => trigger.sql).join("\\n"),\n  worktree: GENERATED_TRIGGERS.worktree.map(trigger => trigger.sql).join("\\n"),\n};\n`;
const destination = fileURLToPath(new URL("../packages/db-core/src/roam/generated.ts", import.meta.url));
if (args[0] === "--check") {
  let current;
  try { current = readFileSync(destination, "utf8"); }
  catch { throw new Error("Generated roaming SQL is missing. Run the generator."); }
  if (current !== output) throw new Error("Generated roaming SQL differs. Run the generator.");
  console.log("Generated roaming SQL matches the descriptors.");
} else {
  writeFileSync(destination, output);
  console.log("Generated roaming SQL for schema 14.");
}
